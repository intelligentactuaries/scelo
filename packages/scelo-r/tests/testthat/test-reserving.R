test_that("Mack on RAA reproduces the published values", {
  g <- golden()$raa
  raa <- raa_triangle()
  m <- sc_mack(raa)
  expect_s3_class(m, "scelo_reserving")
  expect_equal(m$method, "mack")
  expect_equal(round(m$ibnr), 52135)
  expect_equal(round(m$ultimate), 213122)
  expect_equal(round(m$latest), 160987)
  expect_equal(round(m$se), 26909)  # Mack (1993), R ChainLadder est.sigma = "Mack"
  expect_lt(abs(m$cv - 0.52), 0.01)
  se <- round(m$table$se[m$table$origin != "total"])
  expect_equal(se, c(0, 206, 623, 747, 1469, 2002, 2209, 5358, 6333, 24566))
  expect_close(m$factors, g$factors, 1e-10, "factors")
  expect_close(m$cdf, g$cdf, 1e-10, "cdf")
  expect_close(m$detail$sigma2, g$sigma2, 1e-10, "sigma2")
  expect_table_close(sc_df(m$table), split_df(g$mack), 1e-8)
  expect_equal(attr(m$table, "title"), "Mack chain ladder")
  expect_equal(attr(m$table, "basis"), "volume-weighted link ratios · Mack (1993) MSE")
  expect_match(sc_notes(m$table)[1], "^SE is the square root of Mack's MSE")
})

test_that("chain ladder on RAA: factors, cdf, ldf tail", {
  raa <- raa_triangle()
  cl <- sc_chain_ladder(raa)
  expect_equal(cl$method, "chain-ladder")
  expect_close(cl$factors[1:3], c(2.999, 1.624, 1.271), 1e-3, "first factors")
  expect_equal(round(cl$ibnr), 52135)
  expect_lt(abs(sc_cdf(raa)[[1]] - prod(cl$factors)), 1e-9)
  ldf <- sc_ldf(raa)
  expect_equal(names(ldf)[length(ldf)], "tail")
  expect_equal(names(ldf)[1], "0→1")
  expect_equal(names(sc_cdf(raa)), as.character(0:9))
  expect_equal(cl$table$origin, c(as.character(1981:1990), "total"))
  expect_equal(names(cl$table), c("origin", "latest", "cdf", "pct_developed", "ultimate", "ibnr"))
  expect_true(is.na(cl$table$cdf[11]))
  expect_equal(cl$table$ibnr[11], cl$ibnr)
  expect_equal(attr(cl$table, "basis"), "volume-weighted link ratios")
  cl2 <- sc_chain_ladder(raa, average = "simple", n_periods = 3, tail_factor = 1.05)
  expect_equal(attr(cl2$table, "basis"), "simple-weighted link ratios · last 3 · tail 1.05")
  expect_gt(cl2$ibnr, 0)
  expect_equal(unname(sc_ldf(raa, tail_factor = 1.05)[["tail"]]), 1.05)
  expect_equal(sc_latest_diagonal(raa), stats::setNames(c(18834, 16704, 23466, 27067, 26180, 15852, 12314, 13112, 5395, 2063), 1981:1990))
})

