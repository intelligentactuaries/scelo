# Reserving: the RAA triangle (Mack 1993) against the published values the
# Python package reproduces, plus the claims-sample triangle cell by cell.

raa_triangle <- function() sc_from_wide(golden()$raa$triangle, origins = 1981:1990)

# golden reserve tables carry origin as a column; compare every numeric column
expect_table_close <- function(got, want, tol = 1e-6) {
  expect_equal(names(got), names(want))
  expect_equal(as.character(got$origin), as.character(want$origin))
  for (c in setdiff(names(want), "origin")) expect_close(got[[c]], want[[c]], tol, label = c)
}

