test_that("sc_fit ranks the true family first", {
  set.seed(2)
  x <- stats::rlnorm(2000, 8, 1.2)
  f <- sc_fit(x)
  expect_s3_class(f, "scelo_table")
  expect_equal(f$distribution[1], "lognormal")
  expect_true(abs(f$p_mu[1] - 8) < 0.1 && abs(f$p_sigma[1] - 1.2) < 0.1)
  expect_true(all(diff(f$aic) >= 0))
  expect_true(all(f$ks > 0 & f$ks < 1))
  expect_equal(names(f)[1:5], c("distribution", "params", "loglik", "aic", "ks"))
  expect_equal(sc_title(f), "Severity fits · n = 2,000")
  expect_equal(sc_basis(f), "maximum likelihood")
  # closed forms
  lx <- log(x)
  expect_close(f$p_mu[1], mean(lx))
  expect_close(f$p_sigma[1], sqrt(mean((lx - mean(lx))^2)))
  expect_close(f$p_theta[f$distribution == "exponential"], mean(x))
  # the numerical fits satisfy their likelihood equations
  a <- f$p_alpha[f$distribution == "gamma"]
  expect_true(abs(log(a) - digamma(a) - (log(mean(x)) - mean(lx))) < 1e-8)
  k <- f$p_shape[f$distribution == "weibull"]
  expect_true(abs(sum(x^k * lx) / sum(x^k) - 1 / k - mean(lx)) < 1e-8)
  set.seed(4)
  gx <- stats::rgamma(3000, shape = 2, scale = 500)
  expect_equal(sc_fit(gx)$distribution[1], "gamma")
  ps <- sc_lognormal_params(1000, 500)
  expect_true(abs(exp(ps[["mu"]] + ps[["sigma"]]^2 / 2) - 1000) < 1e-9)
  expect_error(sc_fit(c(1, 2, 3)), "need at least 5 positive observations")
})

test_that("credibility golden values and classical standards", {
  g <- golden()
  df <- split_df(g$credibility$data)
  c <- sc_credibility(df, "group", "lr")
  expect_s3_class(c, "scelo_table")
  gt <- split_df(g$credibility$table)
  expect_equal(c$group, gt$group)
  for (col in c("n", "weight", "mean", "Z", "credibility_premium")) expect_close(c[[col]], gt[[col]], label = col)
  expect_equal(sc_basis(c), g$credibility$basis)
  expect_equal(sc_title(c), "Bühlmann–Straub credibility · lr by group")
  expect_equal(sc_credibility(df), c)   # inferred columns
  expect_identical(sc_buhlmann, sc_credibility)
  A <- c[c$group == "A", ]; C <- c[c$group == "C", ]
  expect_true(A$Z > C$Z && C$Z > 0 && A$Z <= 1)
  expect_true(abs(C$credibility_premium - C$mean) > 0)
  expect_equal(round(sc_full_credibility(0.9, 0.05)), 1082)
  expect_close(sc_full_credibility(0.9, 0.05), g$full_credibility)
  expect_true(abs(sc_limited_fluctuation(270.5, p = 0.9, k = 0.05) - 0.5) < 1e-2)
  expect_equal(sc_limited_fluctuation(1e9), 1)
  expect_true(sc_full_credibility(0.9, 0.05, cv = 1) > 2 * sc_full_credibility(0.9, 0.05) - 1e-9)
})

test_that("credibility handles weights, single-record groups and indistinguishable groups", {
  df <- data.frame(group = c("A", "A", "A", "B", "B", "C"), lr = c(0.7, 0.8, 0.75, 0.9, 0.95, 0.5), w = c(10, 20, 30, 5, 5, 1))
  c <- sc_credibility(df, "group", "lr", "w")
  expect_equal(c$group, c("A", "B", "C"))
  expect_equal(c$weight, c(60, 10, 1))
  expect_close(c$mean[1], sum(c(0.7, 0.8, 0.75) * c(10, 20, 30)) / 60)
  expect_true(all(c$Z >= 0 & c$Z <= 1))
  flat <- data.frame(group = rep(c("A", "B"), each = 4), lr = rep(c(0.5, 0.6, 0.5, 0.6), 2))
  f <- sc_credibility(flat)
  expect_equal(f$Z, c(0, 0))
  expect_match(sc_basis(f), "K inf$")
  expect_error(sc_credibility(data.frame(group = c("a", "b"), txt = c("x", "y"))), "pass value=<numeric column>")
})

test_that("aggregate_scr golden values and identity correlation", {
  g <- golden()
  t <- sc_aggregate_scr(c(mortality = 100, longevity = 50, lapse = 200, expense = 80, cat = 40))
  gt <- split_df(g$scr)
  expect_equal(t$module, gt$index)
  for (col in c("charge", "marginal", "share")) expect_close(t[[col]], gt[[col]], label = col)
  scr <- t$charge[t$module == "SCR"]
  expect_true(scr > 0 && scr < 470)
  expect_true(abs(sum(t$marginal, na.rm = TRUE) - scr) < 1e-9)
  expect_equal(sc_notes(t), "SCR = √(vᵀρv) = 304 vs undiversified sum 470 (35.3% diversification). Marginal contributions (Euler) sum to the SCR.")
  expect_equal(sc_basis(t), "SII life correlation matrix")
  ident <- sc_aggregate_scr(c(a = 3, b = 4), corr = diag(2))
  expect_true(abs(ident$charge[ident$module == "SCR"] - 5) < 1e-12)
  expect_equal(sc_basis(ident), "given correlation matrix")
  named <- sc_aggregate_scr(list(a = 3, b = 4), corr = matrix(c(1, 1, 1, 1), 2, dimnames = list(c("a", "b"), c("a", "b"))))
  expect_true(abs(named$charge[named$module == "SCR"] - 7) < 1e-12)
  bscr <- sc_aggregate_scr(c(market = 100, life = 50, non_life = 30), corr = SC_SII_BSCR_CORR)
  expect_true(bscr$charge[bscr$module == "SCR"] < 180)
  expect_equal(dim(SC_SII_LIFE_CORR), c(7, 7))
  expect_true(isSymmetric(SC_SII_LIFE_CORR) && isSymmetric(SC_SII_NONLIFE_CORR) && isSymmetric(SC_SII_BSCR_CORR))
  expect_error(sc_aggregate_scr(c(1, 2)), "modules must be named")
})

