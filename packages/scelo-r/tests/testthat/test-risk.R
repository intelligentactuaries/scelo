  expect_close(attr(nb, "sd"), g$panjer_nb$sd)
  expect_close(nb$VaR[nb$p == 0.995], g$panjer_nb$var995)
})

test_that("other frequencies, empirical severities and the lattice warning", {
  b <- sc_aggregate_loss("binomial", "exponential", m = 10, q = 0.3, theta = 500)
  expect_true(abs(attr(b, "mean") - 10 * 0.3 * 500) < 5)
  bf <- sc_aggregate_loss("binomial", "exponential", m = 10, q = 0.3, theta = 500, method = "fft")
  expect_true(abs(attr(bf, "mean") - attr(b, "mean")) < 1)
  set.seed(7)
  emp <- stats::rgamma(500, 2, scale = 1000)
  e <- sc_aggregate_loss("poisson", emp, lam = 4)
  expect_true(abs(attr(e, "mean") - 4 * mean(emp)) < 0.02 * 4 * mean(emp))
  expect_equal(sc_title(e), "Aggregate loss · poisson(lam=4) × empirical")
  w <- sc_aggregate_loss("poisson", "weibull", lam = 2, shape = 1.5, scale = 1000)
  expect_true(abs(attr(w, "mean") - 2 * 1000 * gamma(1 + 1 / 1.5)) < 5)
  p <- sc_aggregate_loss("negbin", "pareto", r = 2, beta = 1, alpha = 3, theta = 1000, method = "fft")
  expect_true(abs(attr(p, "mean") - 2 * 500) < 10)
  short <- sc_aggregate_loss("poisson", "lognormal", lam = 5, mu = 8, sigma = 1, h = 10, n = 256)
  expect_match(sc_basis(short), "WARNING lattice too short")
  expect_error(sc_aggregate_loss("geometric", "lognormal", lam = 1, mu = 1, sigma = 1), "Panjer frequency must be poisson, negbin or binomial")
  expect_error(sc_aggregate_loss("poisson", "cauchy", lam = 1), "severity must be lognormal, exponential, gamma, pareto or weibull")
})

test_that("sc_panjer reproduces the pmf identities", {
  f <- c(0, 0.5, 0.3, 0.2, rep(0, 396))
  g <- sc_panjer("poisson", f, lam = 2)
  expect_equal(sum(g), 1, tolerance = 1e-12)
  expect_equal(sum((seq_along(g) - 1) * g), 2 * sum((seq_along(f) - 1) * f), tolerance = 1e-12)
  expect_equal(g[1], exp(-2))
  gn <- sc_panjer("negbin", f, r = 2, beta = 1.5)
  expect_equal(sum((seq_along(gn) - 1) * gn), 3 * sum((seq_along(f) - 1) * f), tolerance = 1e-12)
  gb <- sc_panjer("binomial", f, m = 5, q = 0.2)
  expect_equal(sum((seq_along(gb) - 1) * gb), 1 * sum((seq_along(f) - 1) * f), tolerance = 1e-12)
  expect_error(sc_panjer(c(0.5, 0.5), f), "pass a frequency name")
})

