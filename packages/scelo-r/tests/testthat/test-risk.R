test_that("sc_var is the type-7 quantile and sc_tvar sits above it", {
  x <- as.numeric(1:1000)
  expect_equal(sc_var(x, 0.99), unname(stats::quantile(x, 0.99, type = 7)))
  expect_true(sc_tvar(x, 0.99) >= sc_var(x, 0.99))
  expect_identical(sc_es, sc_tvar)
  expect_equal(sc_var(c(x, NA), 0.5), sc_var(x, 0.5))
  expect_equal(sc_tvar(x, 0.999), mean(x[x >= stats::quantile(x, 0.999)]))
})

test_that("aggregate loss methods agree with theory", {
  lam <- 5; mu <- 8; sig <- 1
  mean_theory <- lam * exp(mu + sig^2 / 2)
  sd_theory <- sqrt(lam * exp(2 * mu + 2 * sig^2))
  for (method in c("panjer", "fft")) {
    a <- sc_aggregate_loss("poisson", "lognormal", lam = lam, mu = mu, sigma = sig, method = method)
    expect_true(abs(attr(a, "mean") / mean_theory - 1) < 2e-3, label = method)
    expect_true(abs(attr(a, "sd") / sd_theory - 1) < 5e-3, label = method)
    expect_s3_class(a, "scelo_table")
    expect_equal(names(a), c("p", "VaR", "TVaR"))
    expect_true(all(a$TVaR >= a$VaR))
    expect_match(sc_basis(a), sprintf("^%s · lattice h = ", method))
  }
  mc <- sc_aggregate_loss("poisson", "lognormal", lam = lam, mu = mu, sigma = sig, method = "mc", n_sims = 50000, seed = 1)
  expect_true(abs(attr(mc, "mean") / mean_theory - 1) < 0.03)
  expect_equal(sc_basis(mc), "Monte Carlo · 50,000 simulations")
  nb <- sc_aggregate_loss("negbin", "gamma", r = 3, beta = 2, alpha = 2, theta = 1000)
  expect_true(abs(attr(nb, "mean") - 12000) < 20)
  expect_true(all(nb$TVaR >= nb$VaR))
  expect_equal(sc_title(nb), "Aggregate loss · negbin(r=3, beta=2) × gamma")
})

test_that("Panjer golden values: poisson × lognormal and negbin × gamma", {
  g <- golden()
  a <- sc_aggregate_loss("poisson", "lognormal", lam = 5, mu = 8, sigma = 1, h = 100, n = 4096)
