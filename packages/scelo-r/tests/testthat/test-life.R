test_that("factors match the golden table and the actuarial identities", {
  g <- golden()
  f <- sc_factors(i = 0.04, n = 10)
  G <- split_df(g$factors_4pct_n10)
  expect_equal(names(f), c("age", "äx", "ax", "Ax", "äx:10", "A¹x:10", "10Ex", "Ax:10"))
  expect_equal(names(f), names(G))
  for (c in names(G)) expect_close(f[[c]], G[[c]], 1e-9, label = c)
  d <- 0.04 / 1.04
