test_that("Lee-Carter matches the Python fit and recovers a known drift", {
  g <- golden()
  lc <- sc_lee_carter(split_df(g$lee_carter$data), horizon = 5)
  expect_s3_class(lc, "scelo_lee_carter")
  expect_close(lc$ax, g$lee_carter$ax, 1e-9, label = "ax")
  expect_close(lc$bx, g$lee_carter$bx, 1e-9, label = "bx")
  expect_close(lc$kt, g$lee_carter$kt, 1e-9, label = "kt")
  expect_close(lc$drift, g$lee_carter$drift, 1e-9)
  expect_close(lc$drift_se, g$lee_carter$drift_se, 1e-9)
  G <- split_df(g$lee_carter$forecast)
  expect_equal(names(lc$forecast), c("year", "kt", "rate@65", "lower95", "upper95"))
  for (c in names(G)) expect_close(lc$forecast[[c]], G[[c]], 1e-9, label = c)
  expect_equal(names(lc$ax), as.character(50:90))
  expect_equal(names(lc$kt), as.character(1990:2019))
  # the Python test: synthetic log-linear improvement of 1.5 % a year
  d <- expand.grid(year = 1990:2019, age = 50:90)
  d$qx <- exp(-9 + 0.09 * d$age - 0.015 * (d$year - 1990))
  lc2 <- sc_lee_carter(d, horizon = 5)
  expect_lt(abs(sum(lc2$bx) - 1), 1e-9)
  expect_lt(abs(mean(lc2$kt)), 1e-9)
  expect_gt(lc2$explained, 0.99)
  imp <- 1 - (lc2$forecast[["rate@65"]][5] / lc2$forecast[["rate@65"]][1])^(1 / 4)
  expect_lt(abs(imp - (1 - exp(-0.015))), 1e-3)
  expect_output(print(lc2), "Lee–Carter: 41 ages × 30 years")
  expect_error(sc_lee_carter(d[d$year < 1992, ]), "at least 3 years")
})

