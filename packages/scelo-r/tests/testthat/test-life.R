test_that("sc_qx resolves every basis shape", {
  g <- golden()
  q <- sc_qx(data.frame(age = c(30, 30, 31, 33), qx = c(1.0, 1.2, 1.3, 1.5)))  # percent-shaped, with a gap
  expect_s3_class(q, "scelo_qx")
  expect_equal(q$ages, g$qx_interp$ages)
  expect_close(q$qx, g$qx_interp$qx, 1e-12)
  expect_lt(abs(q$qx[1] - 0.011), 1e-12)
  expect_lt(abs(q$qx[3] - 0.014), 1e-12)
  expect_true(32 %in% q$ages)
  expect_true(any(grepl("percentages", q$notes)))
  expect_true(any(grepl("1 missing age interpolated", q$notes)))
  q2 <- sc_qx(data.frame(age = c(40, 40, 41), deaths = c(1, 1, 3), exposure = c(200, 200, 600)))
  expect_lt(abs(q2$qx[1] - 0.005), 1e-12)
  expect_true(grepl("ungraduated", q2$notes[1]))
  expect_equal(q2$label, "crude qx = `deaths` / `exposure` by `age`")
  q3 <- sc_qx(data.frame(age = c(50, 51, 52), lx = c(1000, 990, 975)))
  expect_lt(abs(q3$qx[1] - 0.01), 1e-12)
  expect_equal(q3$label, "qx derived from `lx` by `age`")
  expect_error(sc_qx(data.frame(foo = 1)), "could not infer the age column")
  # named vector, parameter list, strings
  qv <- sc_qx(stats::setNames(c(0.01, 0.02, 0.04), c(30, 31, 33)))
  expect_equal(qv$ages, 30:33)
  expect_equal(qv$qx, c(0.01, 0.02, 0.03, 0.04))
  expect_equal(qv$label, "qx from `qx` by age")
  qm <- sc_qx()
  expect_equal(qm$ages, 20:110)
  expect_equal(qm$label, "Gompertz–Makeham (illustrative)")
  expect_close(qm$qx, unname(sc_makeham(20:110)), 1e-15)
  qc <- sc_qx(list(A = 0.0003, B = 3e-6, c = 1.12, multiplier = 1.5), ages = c(30, 40))
  expect_equal(qc$label, "Gompertz–Makeham (custom)")
  expect_equal(qc$notes, "Mortality from Gompertz–Makeham μx = A + B·cˣ with A = 0.0003, B = 3e-06, c = 1.12, × 1.5.")
  expect_close(qc$qx[1:3], c(0.00059258, 0.0006097, 0.00062888), 1e-6)
  qg <- sc_qx("gompertz", ages = c(30, 32))
  expect_close(qg$qx, c(9.54910686e-05, 1.07331326e-04, 1.20639607e-04), 1e-7)
  expect_close(unname(sc_gompertz(30:32)), qg$qx, 1e-12)
  expect_identical(sc_qx(qm), qm)
  expect_equal(range(sc_qx(ages = c(NA, 50))$ages), c(20, 50))
  expect_equal(range(sc_qx(ages = c(90, NA))$ages), c(90, 110))
  expect_error(sc_qx(ages = 30), "ages must be c(from, to)", fixed = TRUE)
  expect_error(sc_qx("AM92"), "unknown mortality basis")
  expect_error(sc_qx(stats::setNames(c(0.01, 0.02), c(30, 31)), ages = c(50, 60)), "no ages left")
  expect_identical(sc_qx(qv, ages = c(50, 60)), qv)  # a resolved scelo_qx passes through untouched, like Python's QxTable
  expect_equal(names(as.data.frame(qm)), c("age", "qx"))
  expect_output(print(qm), "Gompertz")
})

