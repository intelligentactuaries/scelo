  expect_close(f$ax, f[["äx"]] - 1, 1e-9, label = "ax = äx - 1")
  ok <- !is.na(f[["Ax:10"]])
  expect_close(f[["Ax:10"]][ok], f[["A¹x:10"]][ok] + f[["10Ex"]][ok], 1e-9, label = "Ax:n = A1x:n + nEx")
  expect_equal(sum(is.na(f[["Ax:10"]])), 10)  # blank where x + n runs past the table
  expect_equal(ncol(sc_factors(i = 0.04)), 4)
  expect_equal(attr(f, "title"), "Annuity & assurance factors · Gompertz–Makeham (illustrative) · i = 4 % · n = 10")
  expect_error(sc_factors(n = -1), "n must be")
})

test_that("premium grid matches the golden tables and the factor identity", {
  g <- golden()
  p <- sc_premium(i = 0.04, product = "term")
  e <- sc_premium(i = 0.04, product = "endowment")
  Gp <- split_df(g$premium_term_4pct)
  Ge <- split_df(g$premium_endow_4pct)
  expect_equal(names(p), c("age", "n=10", "n=15", "n=20", "n=25", "n=30"))
  for (c in names(Gp)) expect_close(p[[c]], Gp[[c]], 1e-9, label = c)
  for (c in names(Ge)) expect_close(e[[c]], Ge[[c]], 1e-9, label = c)
  f <- sc_df(sc_factors(i = 0.04, n = 10))
  row <- f[f$age == 30, ]
  expect_lt(abs(p[p$age == 30, "n=10"] - 1000 * row[["A¹x:10"]] / row[["äx:10"]]), 1e-9)
  expect_true(all(e[["n=10"]] > p[["n=10"]]))
  w <- sc_premium(i = 0.04, product = "whole-life")
  expect_true("whole life" %in% names(w))
  expect_equal(names(sc_premium(product = "Whole Life")), names(w))
  expect_lt(abs(sc_annuity(65, i = 0.04) - f[f$age == 65, "äx"]), 1e-12)
  expect_lt(abs(sc_annuity(65, i = 0.04, due = FALSE) - f[f$age == 65, "ax"]), 1e-12)
  expect_lt(abs(sc_annuity(40, i = 0.04, n = 10) - f[f$age == 40, "äx:10"]), 1e-12)
  expect_lt(abs(sc_assurance(40, i = 0.04) - f[f$age == 40, "Ax"]), 1e-12)
  expect_lt(abs(sc_assurance(40, i = 0.04, n = 10) - f[f$age == 40, "A¹x:10"]), 1e-12)
  expect_lt(abs(sc_assurance(40, i = 0.04, n = 10, endowment = TRUE) - f[f$age == 40, "Ax:10"]), 1e-12)
  expect_error(sc_annuity(200), "age 200 is not in the basis")
  expect_error(sc_premium(product = "annuity"), "product must be term, endowment or whole-life")
  expect_equal(attr(p, "title"), "Net premium per 1,000 SA · term assurance · Gompertz–Makeham (illustrative) · i = 4 %")
  expect_equal(sc_notes(p)[3], "Interest 4 %.")
  # a data-frame basis narrower than the default grid: rows outside the basis are skipped
  pd <- sc_premium(data.frame(age = 20:79, qx = unname(sc_makeham(20:79))), ages = c(30, 40), step = 5, terms = c(10, 20))
  expect_equal(pd$age, c(30, 35, 40))
  expect_close(pd[["n=20"]], c(0.510612, 0.747492, 1.171108), 1e-6)
})

