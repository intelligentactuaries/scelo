test_that("Whittaker-Henderson graduation reproduces the Python numbers and smooths", {
  g <- golden()
  crude <- stats::setNames(g$graduate$crude, g$graduate$ages)
  gr <- sc_graduate(crude, h = 100)
  expect_equal(names(gr), c("age", "crude", "graduated", "residual", "weight"))
  expect_equal(gr$age, g$graduate$ages)
  expect_close(gr$graduated, g$graduate$graduated, 1e-8)
  true <- unname(sc_makeham(30:89))
